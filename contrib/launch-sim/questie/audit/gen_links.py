"""SQL: quest givers / enders from the Forever QuestieDB for quests that have none in our world DB (the quest could not be
taken or turned in), plus the Forever wanted posters. Only spawned NPCs / objects."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import db

D = os.path.dirname(os.path.abspath(__file__))
r = json.load(open(os.path.join(D, 'report.json')))
Q = {int(k): v for k, v in json.load(open(os.path.join(D, 'questie.json')))['quests'].items()}
SKIP = set(range(79000, 80000)) | {7632}  # Season of Discovery ids (Baxtan, Storm, Earth, and Fire); 7632 starts from a looted item
EXTRA_OBJ = {549, 567, 2954}  # Forever wanted posters next to the old givers; Uldum Pedestal

adds = {'creature_queststarter': set(), 'creature_questender': set(), 'gameobject_queststarter': set(),
        'gameobject_questender': set()}
for kind, table in (('sn', 'creature_queststarter'), ('en', 'creature_questender'),
                    ('so', 'gameobject_queststarter'), ('eo', 'gameobject_questender')):
    for x in r.get('link_missing_' + kind, []):
        if x['id'] not in SKIP:
            for e in x['missing_spawned']:
                adds[table].add((e, x['id']))

# only quests without any giver (or ender) of either kind get one, besides the posters
have = {}
for t in adds:
    have[t] = {(int(a), int(b)) for a, b in db.q('SELECT id, quest FROM world.%s' % t)}
start_any = {int(b) for t in ('creature_queststarter', 'gameobject_queststarter') for a, b in
             db.q('SELECT id, quest FROM world.%s' % t)}
end_any = {int(b) for t in ('creature_questender', 'gameobject_questender') for a, b in
           db.q('SELECT id, quest FROM world.%s' % t)}
names = {int(a): b for a, b in db.q('SELECT entry, name FROM world.creature_template')}
gnames = {int(a): b for a, b in db.q('SELECT entry, name FROM world.gameobject_template')}
L = ["-- Quest givers and enders from the Forever QuestieDB (Wowhead Forever data) for quests our world DB had no giver or no",
     "-- ender for, so they could not be taken or turned in; only NPCs and objects spawned here. Also the Forever wanted posters",
     "-- for 549 and 567 next to the old NPC givers, and the Uldum Pedestal for 2954. Generated by the 28 Oct quest audit",
     "-- (doc/ForeverQuestGaps.md). Safe to run again."]
flag = set()
for t in ('creature_queststarter', 'creature_questender', 'gameobject_queststarter', 'gameobject_questender'):
    rows = []
    for e, q in sorted(adds[t], key=lambda p: (p[1], p[0])):
        if (e, q) in have[t]:
            continue
        starter = 'starter' in t
        if q not in EXTRA_OBJ and ((starter and q in start_any) or (not starter and q in end_any)):
            continue
        nm = (names if t.startswith('creature') else gnames).get(e, '?')
        rows.append("(%d, %d)%s -- %s: %s" % (e, q, '%s', Q.get(q, {}).get('name', '?'), nm))
        if t.startswith('creature'):
            flag.add(e)
    if rows:
        L.append("INSERT IGNORE INTO `%s` (`id`, `quest`) VALUES" % t)
        for i, row in enumerate(rows):
            L.append(row % (',' if i < len(rows) - 1 else ';'))
if flag:
    L.append("UPDATE `creature_template` SET `npcflag` = `npcflag` | 2 WHERE `entry` IN (%s);" %
             ', '.join(str(e) for e in sorted(flag)))
open(sys.argv[1], 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('\n'.join(L))
